"""Generate the N32H7xx pin/alternate-function table for the pinctrl driver.

The vendor function-remap database lists, for every peripheral signal, the
package pins and the alternate-function index that route it.  That mapping is
a property of the series, not of any particular board, so it is compiled into
the pin controller instead of being repeated in every device tree.

Usage: gen-pinfunc.py <fucremap.dat> <output.h>
"""

import re
import sys

PORTS = "ABCDEFGHIJK"
PINS_PER_PORT = 16
NPINS = len(PORTS) * PINS_PER_PORT

LINE_RE = re.compile(r"^(?P<signal>[A-Za-z0-9_.\-]+)\s*:\s*(?P<pins>.*)$")
PIN_RE = re.compile(r"^(?P<port>P[A-K])(?P<pin>\d{1,2})/(?P<af>-?\d+)$")
VALID_SIGNAL_RE = re.compile(r"^[A-Za-z0-9_.\-]+$")


def sanitize(signal):
    name = signal.lower().replace(".", "_").replace("-", "_")
    name = re.sub(r"_+", "_", name).strip("_")
    return name


def parse(path):
    """Return {pin_number: {function_name: af}} plus the pin set."""
    funcs = {}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            m = LINE_RE.match(line)
            if not m:
                continue
            signal = m.group("signal")
            if not VALID_SIGNAL_RE.match(signal):
                # Wildcard groups such as "SHRTIM1.FALT*1~6" are not single
                # routable signals; they only repeat other entries.
                continue
            name = sanitize(signal)
            if not name:
                continue
            for item in m.group("pins").split(","):
                item = item.strip()
                pm = PIN_RE.match(item)
                if not pm:
                    continue
                af = int(pm.group("af"))
                if af < 0:
                    # "ALL/-1" means every pin can be an analog input; that is
                    # expressed with the dedicated "analog" function instead.
                    continue
                port = PORTS.index(pm.group("port")[1])
                pin = int(pm.group("pin"))
                if not 0 <= pin < PINS_PER_PORT:
                    continue
                number = port * PINS_PER_PORT + pin
                per_pin = funcs.setdefault(number, {})
                # A signal can legitimately appear twice on the same pin only
                # through the wildcard groups we dropped; keep the first.
                per_pin.setdefault(name, af)
    return funcs


def emit(fh, funcs):
    pins = sorted(funcs)
    for number in pins:
        port = PORTS[number // PINS_PER_PORT]
        pin = number % PINS_PER_PORT
        fh.write("static const struct n32h7xx_pin_function "
                 "n32h7xx_pinfunc_p%s%d[] = {\n" % (port.lower(), pin))
        for name in sorted(funcs[number]):
            fh.write('\t{ "%s", %d },\n' % (name, funcs[number][name]))
        fh.write("};\n\n")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    funcs = parse(src)

    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(
            "/* SPDX-License-Identifier: GPL-2.0-only */\n"
            "/*\n"
            " * NSING N32H7xx pin / alternate-function table.\n"
            " *\n"
            " * Generated by scripts/nsing/pinctrl/gen-pinfunc.py from the\n"
            " * vendor N32H76x_H78x_FucRemap.dat database.  Do not edit by hand;\n"
            " * re-run the script instead.\n"
            " */\n\n"
            "#ifndef __PINCTRL_N32H7XX_PINFUNC_H\n"
            "#define __PINCTRL_N32H7XX_PINFUNC_H\n\n"
            "#include <linux/types.h>\n\n"
            "struct n32h7xx_pin_function {\n"
            "\tconst char *name;\n"
            "\tu8 af;\n"
            "};\n\n"
            "struct n32h7xx_desc_pin {\n"
            "\tunsigned int number;\n"
            "\tconst char *name;\n"
            "\tconst struct n32h7xx_pin_function *functions;\n"
            "\tunsigned int nfunctions;\n"
            "};\n\n"
            "#define N32H7XX_NPINS %d\n\n" % NPINS)
        emit(fh, funcs)
        fh.write("static const struct n32h7xx_desc_pin "
                 "n32h7xx_pins[N32H7XX_NPINS] = {\n")
        for port_idx, port in enumerate(PORTS):
            for pin in range(PINS_PER_PORT):
                number = port_idx * PINS_PER_PORT + pin
                if number in funcs:
                    fh.write('\t{ .number = %d, .name = "P%s%d", '
                             '.functions = n32h7xx_pinfunc_p%s%d, '
                             '.nfunctions = %d },\n'
                             % (number, port, pin, port.lower(), pin,
                                len(funcs[number])))
                else:
                    fh.write('\t{ .number = %d, .name = "P%s%d", '
                             '.functions = NULL, .nfunctions = 0 },\n'
                             % (number, port, pin))
        fh.write("};\n\n#endif /* __PINCTRL_N32H7XX_PINFUNC_H */\n")

    total = sum(len(v) for v in funcs.values())
    print("%s: %d pins, %d function entries" % (dst, len(funcs), total))


if __name__ == "__main__":
    main()
